abstract final class SafLimits {
  static const maxDocuments = ${values['max_documents']};
  static const maxDepth = ${values['max_depth']};
  static const maxRelativePathBytes = ${values['max_relative_path_bytes']};
  static const maxAggregatePathBytes = ${values['max_aggregate_path_bytes']};
  static const maxNoteBytes = ${values['max_note_bytes']};
  static const maxReadBatchNotes = ${values['max_read_batch_notes']};
  static const maxReadBatchBytes = ${values['max_read_batch_bytes']};
  static const maxConcurrentNoteReads = ${values['max_concurrent_note_reads']};
  static const maxScanNoteBytes = ${values['max_scan_note_bytes']};
}
''';

